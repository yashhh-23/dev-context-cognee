"""bug_service.py — Cognee-powered GitHub issue draft generator.

Takes a code snippet + optional error message, searches Cognee memory for
similar past bugs, then uses the LLM layer to produce a structured issue body.
"""
from __future__ import annotations

import textwrap
from typing import Optional
import json
import cognee
from app.services.recall_service import extract_text


async def draft_github_issue(
    snippet: str,
    error_message: Optional[str] = None,
    language: str = "unknown",
    file_path: str = "",
) -> dict:
    """Return a dict with `title`, `body`, and `labels` for a GitHub issue."""

    # 1. Build a recall query from the snippet + error
    query_parts = []
    if error_message:
        query_parts.append(f"Error: {error_message}")
    query_parts.append(f"Language: {language}")
    query_parts.append(f"Snippet (first 300 chars): {snippet[:300]}")
    recall_query = "\n".join(query_parts)

    # 2. Recall similar bugs from Cognee memory
    similar_memories: list[str] = []
    try:
        results = await cognee.recall(recall_query)
        items = results if isinstance(results, list) else [results] if results else []
        for r in items[:3]:
            text = extract_text(r)
            if text:
                similar_memories.append(text[:400])
    except Exception:
        pass  # memory may be empty on first run

    # 3. Build prompt for LLM
    similar_section = ""
    if similar_memories:
        joined = "\n---\n".join(similar_memories)
        similar_section = f"""
## Similar past issues recalled from memory
{joined}
"""

    prompt = textwrap.dedent(f"""
        You are a senior engineer writing a GitHub issue for a bug.
        Produce a JSON object with exactly these keys:
          - title   (string, ≤72 chars, imperative mood)
          - body    (string, Markdown, includes ## Description, ## Steps to Reproduce,
                    ## Expected vs Actual, ## Snippet section with fenced code block,
                    and optionally ## Related Past Issues if similar memories exist)
          - labels  (array of strings, choose from: bug, needs-triage, {language})

        File: {file_path or 'unknown'}
        Language: {language}
        Error message: {error_message or 'not provided'}

        Code snippet:
        ```{language}
        {snippet[:800]}
        ```
        {similar_section}
        Respond with only the JSON object, no markdown fences around it.
    """)

    # 4. Call Cognee's LLM layer
    try:
        raw = await cognee.llm_query(prompt)
        # strip any accidental code fences
        clean = raw.strip().lstrip("```json").lstrip("```").rstrip("```").strip()
        result = json.loads(clean)
        return {
            "title": result.get("title", "Bug: unexpected error"),
            "body": result.get("body", ""),
            "labels": result.get("labels", ["bug", "needs-triage"]),
            "similar_count": len(similar_memories),
        }
    except Exception as exc:
        # Graceful fallback — return a minimal but valid draft
        fallback_body = textwrap.dedent(f"""
            ## Description
            An error occurred in `{file_path or 'unknown'}` ({language}).

            ## Error
            ```
            {error_message or 'No error message provided'}
            ```

            ## Snippet
            ```{language}
            {snippet[:600]}
            ```

            ## Notes
            _Auto-generated by Dev-Context. LLM draft failed: {exc}_
        """)
        return {
            "title": f"Bug in {file_path.split('/')[-1] or 'unknown file'}",
            "body": fallback_body.strip(),
            "labels": ["bug", "needs-triage"],
            "similar_count": len(similar_memories),
        }

